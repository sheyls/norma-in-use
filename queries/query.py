"""SPARQL over a NORMA-O bundle, with the LOCAL ontology loaded alongside.

    .venv/bin/python queries/query.py --list                       # the prepared queries
    .venv/bin/python queries/query.py 07_cases                     # run one (prefix match)
    .venv/bin/python queries/query.py 09 --bind case=L07_withdraw_8m
    .venv/bin/python queries/query.py -q 'SELECT ?n WHERE { ?n a norma:Prohibition }'
    .venv/bin/python queries/query.py 10 --csv out.csv

The default data is the test contract as generated by the engine (residential-lease/generated/lease.bundle.ttl). The
bundle's owl:imports are never followed: the ontology and the derivation
module come from the installed norma-o package (norma_o.load). The prefix `:` is the bundle's own
namespace and `der:` its derived graph, both detected from the data.
"""
from __future__ import annotations

import argparse
import csv
import sys
from collections import Counter
from pathlib import Path

import norma_o
from rdflib import Graph, Literal, Namespace, URIRef
from rdflib.namespace import RDF

HERE = Path(__file__).resolve().parent
ROOT = HERE.parent
DATA = ROOT / "residential-lease" / "generated" / "lease.bundle.ttl"
NORMA = Namespace("https://w3id.org/def/norma-o#")
NORMAD = Namespace("https://w3id.org/def/norma-o/deriv#")
KINDS = ["Obligation", "Prohibition", "Permission", "Facultative", "Recommendation", "NegativeRecommendation", "ConstitutiveRule"]


def load(data: Path = DATA) -> tuple[Graph, str, str]:
    g = norma_o.load(data)            # the bundle + the NORMA-O IRIs it imports, from the package
    ns = lambda u: str(u)[: str(u).rfind("#") + 1]
    base = Counter(ns(n) for k in KINDS for n in g.subjects(RDF.type, NORMA[k])).most_common(1)[0][0]
    dg = next(g.objects(None, NORMAD.derivedGraph), None)
    derived = str(dg).rstrip("#") + "#" if dg is not None else base.rstrip("#") + "/derived#"
    return g, base, derived


def prefixes(base: str, derived: str) -> str:
    return "".join(f"PREFIX {p}: <{n}>\n" for p, n in (
        ("", base), ("der", derived), ("norma", NORMA), ("normad", NORMAD),
        ("gap", "https://example.org/norma-gap#"), ("rdf", "http://www.w3.org/1999/02/22-rdf-syntax-ns#"),
        ("rdfs", "http://www.w3.org/2000/01/rdf-schema#"), ("owl", "http://www.w3.org/2002/07/owl#"),
        ("skos", "http://www.w3.org/2004/02/skos/core#"), ("prov", "http://www.w3.org/ns/prov#"),
        ("xsd", "http://www.w3.org/2001/XMLSchema#")))


def short(g: Graph, v, base: str, derived: str) -> str:
    if v is None:
        return ""
    if isinstance(v, URIRef):
        s = str(v)
        for pre in (derived, base):
            if s.startswith(pre):
                return s[len(pre):]
        try:
            return g.namespace_manager.curie(v)
        except Exception:
            return s
    return str(v)


def run(g: Graph, base: str, derived: str, text: str, bind: dict[str, str] | None = None):
    init = {k: URIRef(v if v.startswith("http") else base + v) for k, v in (bind or {}).items()}
    res = g.query(prefixes(base, derived) + text, initBindings=init)
    cols = [str(v) for v in res.vars]
    return cols, [[short(g, r[c], base, derived) for c in cols] for r in res]


def resolve(name: str) -> Path:
    p = Path(name)
    if p.suffix == ".rq" and p.exists():
        return p
    hits = sorted(HERE.glob(f"{name}*.rq"))
    if len(hits) != 1:
        raise SystemExit(f"query {name!r}: {len(hits)} matches in {HERE}")
    return hits[0]


def describe(p: Path) -> str:
    first = [l[1:].strip() for l in p.read_text().splitlines() if l.startswith("#")]
    return first[0] if first else ""


def print_table(cols, rows, limit: int) -> None:
    shown = rows[:limit]
    w = [min(60, max([len(c)] + [len(r[i]) for r in shown])) for i, c in enumerate(cols)]
    fmt = "  ".join(f"{{:{x}.{x}}}" for x in w)
    print(fmt.format(*cols)); print(fmt.format(*["-" * x for x in w]))
    for r in shown:
        print(fmt.format(*r))
    print(f"({len(rows)} rows{'' if len(rows) <= limit else f', {limit} shown'})")


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("query", nargs="?", help="prepared query name (prefix) or a .rq file")
    ap.add_argument("-q", "--sparql", help="inline SPARQL (prefixes are added)")
    ap.add_argument("--list", action="store_true")
    ap.add_argument("--bind", action="append", default=[], help="var=value, e.g. case=L07_withdraw_8m")
    ap.add_argument("--data", type=Path, default=DATA)
    ap.add_argument("--csv", type=Path)
    ap.add_argument("--limit", type=int, default=200)
    a = ap.parse_args()

    if a.list:
        for p in sorted(HERE.glob("*.rq")):
            print(f"{p.stem:28} {describe(p)}")
        return 0
    if not (a.query or a.sparql):
        ap.error("give a query name, a .rq file, -q or --list")
    text = a.sparql if a.sparql else resolve(a.query).read_text()
    g, base, derived = load(a.data)
    cols, rows = run(g, base, derived, text, dict(b.split("=", 1) for b in a.bind))
    if a.csv:
        with a.csv.open("w", newline="") as f:
            csv.writer(f).writerows([cols] + rows)
        print(f"{len(rows)} rows -> {a.csv}")
    else:
        print_table(cols, rows, a.limit)
    return 0


if __name__ == "__main__":
    sys.exit(main())
